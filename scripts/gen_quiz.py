# ── Read existing 65 questions ──────────────────────────────────────────────
def read_existing():
    with open(QUIZ_BANK_PATH, 'r', encoding='utf-8') as f:
        text = f.read()
    lines = []
    for line in text.splitlines():
        s = line.strip()
        if re.match(r'Object\.freeze\(\{ id: "q\d+"', s):
            # Only keep the original 65 (q001-q065) to avoid duplication
            m = re.search(r'id: "(q\d+)"', s)
            if m:
                num = int(m.group(1)[1:])
                if num <= 65:
                    lines.append(s)
    return lines

