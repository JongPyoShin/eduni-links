def make_line(qid, cat, question, a1, a2, a3, a4, ans, exp):
    return (
        f'  Object.freeze({{ id: "{qid}", category: "{cat}", '
        f'question: "{question}", '
        f'choices: Object.freeze(['
        f'Object.freeze({{ id: "a", label: "{a1}" }}), '
        f'Object.freeze({{ id: "b", label: "{a2}" }}), '
        f'Object.freeze({{ id: "c", label: "{a3}" }}), '
        f'Object.freeze({{ id: "d", label: "{a4}" }})'
        f']), answer: "{ans}", explanation: "{exp}" }}),'
    )

def main():
    existing_lines = read_existing()

    new_lines = []
    for item in NEW_QUESTIONS:
        qid, cat, q, a1, a2, a3, a4, ans, exp = item
        new_lines.append(make_line(qid, cat, q, a1, a2, a3, a4, ans, exp))

    if len(new_lines) != 200:
        print(f"ERROR: Expected 200 new questions, got {len(new_lines)}", file=sys.stderr)
        sys.exit(1)

    header = 'export const BIRD_QUIZ_BANK = Object.freeze(['
    footer = ']);'
    all_lines = existing_lines + new_lines

    output = header + '\n' + '\n'.join(all_lines) + '\n' + footer + '\n'

    with open(QUIZ_BANK_PATH, 'w', encoding='utf-8') as f:
        f.write(output)

    print(f"Written {len(all_lines)} questions to {QUIZ_BANK_PATH}")

if __name__ == '__main__':
    main()
