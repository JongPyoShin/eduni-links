def parent_guide(mid: str, step: int, answers: dict[str, Any], *, legacy: bool = False) -> list[str]:
    if type(step) is not int or not 0 <= step < 5:
        raise ValueError("invalid guide step")
    if legacy:
        return LEGACY_GUIDES[step]
    if mid == "playground" and step > 0:
        issue = answers.get("0")
        if type(issue) is int and 0 <= issue < 3:
            return PLAY_GUIDES[str(issue)][step - 1]
    return GUIDES[mid][step]


def render_parent_guide(mid: str, step: int, answers: dict[str, Any], tip: str, *, legacy: bool = False) -> None:
    focus, explain, ask, scaffold = parent_guide(mid, step, answers, legacy=legacy)
    with ui.expansion("부모 도움말 · 지도 포인트", icon="school").classes("w-full"):
        ui.label("아이의 답을 대신 고르기보다 생각할 시간을 주세요.").classes("text-caption text-grey-8")
        for label, content in (
            ("이번 단계에서 가르칠 핵심", focus),
            ("이렇게 설명해 주세요", explain),
            ("아이에게 물어볼 질문", ask),
            ("막히면 이렇게 도와주세요", scaffold),
            ("진행 시 유의할 점", tip),
        ):
            with ui.column().classes("w-full gap-1 q-mb-sm"):
                ui.label(label).classes("text-weight-bold text-teal-9")
                ui.label(content).classes("text-body2").style("white-space: normal; overflow-wrap: anywhere;")
